function scrollCardIntoView(card) {

 
  const outer      = card.closest('.works-row-outer');
  const scrollArea = document.getElementById('scroll-area');
  const wrap       = card.querySelector('.work-img-wrap');
 
  function doScroll() {
    if (outer) {
      const outerW  = outer.clientWidth;
      const cardW   = card.offsetWidth;
 
      const cardLeft = card.offsetLeft;
 
      let target;
      if (cardW >= outerW) {
        target = cardLeft;
      } else {
        target = cardLeft - (outerW - cardW) / 2;
      }
 
      const maxScroll = outer.scrollWidth - outerW;
      target = Math.max(0, Math.min(target, maxScroll));
 
      outer.scrollTo({ left: target, behavior: 'smooth' });
    }
 
    if (scrollArea) {
      const areaRect = scrollArea.getBoundingClientRect();
      const cardRect = card.getBoundingClientRect();
      const areaH    = scrollArea.clientHeight;
      const cardH    = card.offsetHeight;
 
      const cardTop    = cardRect.top    - areaRect.top  + scrollArea.scrollTop;
      const cardBottom = cardRect.bottom - areaRect.top  + scrollArea.scrollTop;
      const currentTop = scrollArea.scrollTop;
      const currentBot = currentTop + areaH;
 
      if (cardTop < currentTop + 60 || cardBottom > currentBot - 60) {
        const target = cardTop - (areaH - cardH) / 2;
        scrollArea.scrollTo({ top: target, behavior: 'smooth' });
      }
    }
  }
 
  if (!wrap) { setTimeout(doScroll, 520); return; }
 
  let done = false;
  function onEnd(e) {
    if (e && e.propertyName !== 'width' && e.propertyName !== 'height') return;
    if (done) return;
    done = true;
    wrap.removeEventListener('transitionend', onEnd);
    doScroll();
  }
 
  wrap.addEventListener('transitionend', onEnd);
  setTimeout(onEnd, 520);
}
 
function handleCardClick(work, sid, seriesNode, card) {
  const clickedSameCard = expandedId === work.id;
 
  collapseAll();
 
  if (clickedSameCard) return;
 
  expandedId = work.id;
  card.classList.add('expanded');
  sizeCard(card, EXPAND_H());
  scrollCardIntoView(card);
 
  const dp = document.getElementById(`dp-${sid}`);
  const tags = (work.tags||[]).map(t => `<span class="dp-tag">${t}</span>`).join('');
  dp.innerHTML = `
    <div class="detail-inner">
      <button class="dp-close" onclick="collapseAll()">✕ Close</button>
      <div class="dp-field"><div class="dp-lbl">Title</div><div class="dp-val">${work.title}</div></div>
      <div class="dp-field"><div class="dp-lbl">Medium</div><div class="dp-val">${work.medium}</div></div>
      ${work.size ? `<div class="dp-field"><div class="dp-lbl">Size</div><div class="dp-val">${work.size}</div></div>` : ''}
      ${work.desc ? `<div class="dp-desc">${work.desc}</div>` : ''}
      ${tags ? `<div class="dp-tags">${tags}</div>` : ''}
    </div>`;
  requestAnimationFrame(() => dp.classList.add('open'));
 
  updateMobInfo({ ...work, year: seriesNode.dataset.year });
}
 
function collapseAll() {
  if (expandedId === null) return;
 
  const expanded = document.querySelector('.work-card.expanded');
  if (expanded) {
    expanded.classList.remove('expanded');
    sizeCard(expanded, ROW_H());
 
  }
 
  document.querySelectorAll('.detail-panel.open').forEach(p => p.classList.remove('open'));
 
  expandedId = null;
}
 
function setupObserver() {
  if (observer) observer.disconnect();
  const root = document.getElementById('scroll-area');
  observer = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting && e.target.classList.contains('series-node')) {
        activate(e.target.dataset.sid, e.target.dataset.year);
      }
    });
  }, { root, rootMargin: '-25% 0px -55% 0px', threshold: 0 });
  document.querySelectorAll('.series-node').forEach(el => observer.observe(el));
}
 
function activate(sid, year) {
  activeId = sid;
  document.querySelectorAll('.series-node').forEach(el  => el.classList.toggle('in-view', el.dataset.sid === sid));
  document.querySelectorAll('.year-node').forEach(el    => el.classList.toggle('in-view', el.dataset.year === year));
  document.querySelectorAll('.sb-item').forEach(el      => el.classList.toggle('active', el.dataset.sid === sid));
  document.querySelectorAll('.sb-year-row').forEach(el  => el.classList.toggle('active', el.dataset.year === year));
  document.querySelector(`.sb-item[data-sid="${sid}"]`)?.scrollIntoView({ behavior:'smooth', block:'nearest' });
  const node = allSeriesNodes().find(n => n.sid === sid);
  if (node) {
    document.getElementById('tb-name').textContent = node.s.name || node.s.works[0]?.title || '';
    if (node.s.works[0]) updateMobInfo({ ...node.s.works[0], year: node.year });
  }
}
 
function getRelTop(el) {
  const inner = document.getElementById('main-inner');
  let top = 0, cur = el;
  while (cur && cur !== inner) { top += cur.offsetTop; cur = cur.offsetParent; }
  return top;
}
function scrollToSeries(sid) {
  const el = document.querySelector(`.series-node[data-sid="${sid}"]`);
  if (!el) return;
  document.getElementById('scroll-area').scrollTo({ top: getRelTop(el) - 60, behavior:'smooth' });
}
function scrollToYear(year) {
  const el = document.querySelector(`.year-node[data-year="${year}"]`);
  if (!el) return;
  document.getElementById('scroll-area').scrollTo({ top: getRelTop(el) - 12, behavior:'smooth' });
}
