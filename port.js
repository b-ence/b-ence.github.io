function updateFade(outer) {
  const scrolled  = outer.scrollLeft;
  const maxScroll = outer.scrollWidth - outer.clientWidth;
  const threshold = 16;
 
  const fadeLeft  = scrolled > threshold;
  const fadeRight = maxScroll > threshold && scrolled < maxScroll - threshold;
 
  let mask = '';
  if (fadeLeft && fadeRight) {
    mask = 'linear-gradient(to right, transparent 0, black 48px, black calc(100% - 48px), transparent 100%)';
  } else if (fadeLeft) {
    mask = 'linear-gradient(to right, transparent 0, black 48px, black 100%)';
  } else if (fadeRight) {
    mask = 'linear-gradient(to right, black calc(100% - 48px), transparent 100%)';
  }
 
  outer.style.webkitMaskImage = mask;
  outer.style.maskImage       = mask;
}
 
function setupWheelScroll(outer) {
  outer.addEventListener('wheel', e => {
    const overflows = outer.scrollWidth > outer.clientWidth + 2;
    if (!overflows) return;         

    if (outer.querySelector('.work-card.expanded')) return;
 
    e.preventDefault();             
    outer.scrollLeft += e.deltaY;
    updateFade(outer);
  }, { passive: false });
 
  outer.addEventListener('scroll', () => updateFade(outer), { passive: true });
}
 
function initAllWheelScroll() {
  if (!window.matchMedia('(pointer: fine)').matches) return;
 
  document.querySelectorAll('.works-row-outer').forEach(outer => {
    if (outer.dataset.wheelReady) return;
    outer.dataset.wheelReady = '1';
    setupWheelScroll(outer);
    updateFade(outer);
  });
}
 
 
